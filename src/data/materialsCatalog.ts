const materialsByIdNullProto = Object.create(null) as Record<string, MaterialDef>;
for (const mat of MATERIALS_CATALOG) {
  materialsByIdNullProto[mat.id] = mat;
}

export const MATERIALS_BY_ID: Record<string, MaterialDef> = materialsByIdNullProto;

export function isValidMaterialId(id: string): boolean {
  return typeof id === 'string' && Object.hasOwn(MATERIALS_BY_ID, id);
}

export function getMaterialById(id: string): MaterialDef {
  return isValidMaterialId(id) ? MATERIALS_BY_ID[id] : MATERIALS_BY_ID['blanc-alpin'];
}

export function getMaterialsByCategory(category: MaterialCategory): MaterialDef[] {
  return MATERIALS_CATALOG.filter((mat) => mat.category === category);
}
